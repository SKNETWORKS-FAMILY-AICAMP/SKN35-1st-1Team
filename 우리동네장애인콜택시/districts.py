_PREFIX_PATTERN = re.compile(r"^(서울특별시|서울시|서울)\s*")


def normalize_district_name(raw: str | None) -> str | None:
    """원본 자치구 표기를 서울 25개 자치구 표준명으로 변환한다.

    "강남", "강남구", "서울 강남구", "서울특별시 강남구", 앞뒤 공백 등을 모두 처리한다.
    표준 25개 구 목록과 일치하지 않으면 임의로 매핑하지 않고 None을 반환한다.
    """
    if raw is None:
        return None
    value = str(raw).strip()
    if not value:
        return None
    value = _PREFIX_PATTERN.sub("", value).strip()
    if not value:
        return None
    if not value.endswith("구"):
        value = f"{value}구"
    return value if value in SEOUL_DISTRICTS else None


