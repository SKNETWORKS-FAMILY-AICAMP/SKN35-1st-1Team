TIME_GROUPS: list[tuple[str, range]] = [
    ("새벽(00-06시)", range(0, 6)),
    ("오전(06-12시)", range(6, 12)),
    ("오후(12-18시)", range(12, 18)),
    ("저녁/야간(18-24시)", range(18, 24)),
]


def hour_to_time_group(hour: int) -> str:
    for label, hour_range in TIME_GROUPS:
        if hour in hour_range:
            return label
    return "알수없음"
